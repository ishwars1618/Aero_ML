    def forward_display(self, input, tau=1.0):
        """Like forward(), but returns heatmaps ready to plot rather than to train on.

        Runs in .eval() mode under no_grad, restoring the previous mode afterwards,
        and returns (logits, probs) as lists of (B, C, H, W) tensors detached on the
        CPU. They are lists because display code loops over them without knowing how
        many outputs a given model produces; this one produces a single heatmap, so
        both lists have length 1.

        tau -- temperature applied to the logits before the softmax:
               probs = softmax(logits / tau). Below 1.0 sharpens the distribution,
               which matters when a soft-argmax reads coordinates off it: a flat
               heatmap pulls the estimate toward the image centre. 1.0 leaves the
               logits alone. The returned logits are always the raw ones.
        """
        was_training = self.training
        self.eval()
        with torch.no_grad():
            logits = self(input)
            probs = self.heatmap_softmax(logits / tau)
        if was_training:
            self.train()
        return [logits.cpu()], [probs.cpu()]

    def heatmap_softmax(self, heatmap):
        """Spatial softmax of the output logits: normalize over H*W per channel.

        Shapes are taken from the tensor, so no model_image_size global is needed and
        a batch of any size (including 1, for visualization) works unchanged.
        """
        b, c, h, w = heatmap.shape
        return F.softmax(heatmap.reshape(b, c, h * w), dim=2).reshape(b, c, h, w)

    def error(self, heatmap_logits, target, criterion=None,
              batch_size=None, loss_scale=1.0):
        """Spatial-softmax the output logits and score them against target.

        heatmap_logits -- what forward() returned.
        batch_size     -- if given, scale by (actual batch / batch_size) so a short
                          final batch contributes proportionally rather than equally.
        loss_scale     -- constant factor to lift the loss out of the range the
                          softmax leaves it in (probabilities over h*w cells are ~1e-5,
                          so MSE against them is ~1e-10 before scaling).

        Returns the loss alone. Callers that need the probabilities themselves --
        display code -- get them from forward_display().
        """
        predicted = self.heatmap_softmax(heatmap_logits)
        err = (criterion if criterion is not None else self.criterion)(predicted, target)
        if batch_size:
            err = err * predicted.shape[0] / batch_size
        return err * loss_scale


