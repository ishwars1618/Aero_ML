class _ContiguousGrad(torch.autograd.Function):
    """Identity in the forward pass; makes the gradient contiguous on the way back.

    Works around a torch 2.1.0 MPS bug: nn.Conv2d's backward produces garbage when its
    grad_output is non-contiguous (verified: cosine similarity vs the CPU result ~0.007
    for grad_input and ~0.003 for grad_weight -- i.e. noise, not error).

    ChannelLayerNorm ends in a permute, and that permute's backward hands exactly such a
    non-contiguous tensor to whatever conv feeds it. In VisionTransformer every
    MultiHeadVisionAttention routes `combine` and `resnorm.res_conv` into a
    ChannelLayerNorm, so on MPS every parameter upstream of the last one -- all three
    attention blocks, norm1, resizechannels and learnable_ape -- received noise instead
    of a gradient, and the model never learned. The decoder, which sits downstream of
    every ChannelLayerNorm, trained correctly, which is why the symptom was a loss
    pinned at the uniform-heatmap floor rather than a divergence.

    Applying this to the *input* is what matters: it is the gradient LEAVING this module
    toward the conv that has to be contiguous. Making the forward output contiguous does
    nothing, since that never touches the backward tensor.
    """
    @staticmethod
    def forward(ctx, x):
        return x

    @staticmethod
    def backward(ctx, grad_output):
        return grad_output.contiguous()


class ChannelLayerNorm(nn.LayerNorm):
    def __init__(self, num_channels, channel_dim, num_dims):
        super(ChannelLayerNorm, self).__init__(num_channels)
        # build ro
        ro = []
        for i in range(num_dims-1):
            if i >= channel_dim:
                ro.append(i+1)
            else:
                ro.append(i)
        ro.append(channel_dim)

        ro_inv = []
        for i in range(num_dims):
            if i == channel_dim:
                ro_inv.append(num_dims-1)
            elif i > channel_dim:
                ro_inv.append(i-1)
            else:
                ro_inv.append(i)
        
        self.ro = tuple(ro)
        self.ro_inv = tuple(ro_inv)

        print(self.ro)
        print(self.ro_inv)

    def forward(self, x):
        # See _ContiguousGrad: without this the conv feeding this module gets a
        # non-contiguous grad_output and silently returns noise on MPS.
        x = _ContiguousGrad.apply(x)
        x_perm = torch.permute(x, self.ro)
        layernorm_x = super().forward(x_perm)
        return torch.permute(layernorm_x, self.ro_inv)


