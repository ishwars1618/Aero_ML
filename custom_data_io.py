class FramesFromCSV(Dataset):
    def __init__(self, config, transform=None, geo_transform=None,
                 post_geo_transform=None):
        """
        Args:
            config: DataConfig supplying csv_path, images_dir, image_pattern,
                image_size, model_image_size, num_landmarks and heatmap settings
            transform: optional torchvision transform applied to the PIL image
            geo_transform: optional joint (image, points) transform
            post_geo_transform: optional transform applied after geo_transform
        """
        self.config = config
        self.images_dir = config.images_dir
        self.image_pattern = config.image_pattern
        self.transform = transform
        self.geo_transform = geo_transform
        self.post_geo_transform = post_geo_transform

        # Load CSV into numpy array, skipping header
        self.data = np.loadtxt(config.csv_path, delimiter=",", skiprows=1)
        # Ensure it's 2D even if only one row
        if self.data.ndim == 1:
            self.data = np.expand_dims(self.data, axis=0)

        self.frame_numbers = self.data[:, 0].astype(int)
        self.points = self.data[:, 1:]

    def __len__(self):
        return len(self.data)

    def __getitem__(self, idx):
        cfg = self.config
        frame_num = self.frame_numbers[idx]
        coords = self.points[idx]

        # Load image
        img_path = os.path.join(self.images_dir, self.image_pattern.format(frame=frame_num))
        image = Image.open(img_path).convert("RGB")

        # Reshape coords into Nx2 array (x, y)
        coords = coords.reshape(-1, 2)
        coords = torch.tensor(coords, dtype=torch.float32)

        if self.transform:
            image = self.transform(image)
        if self.geo_transform:
            image, coords = self.geo_transform(image, coords)
        if self.post_geo_transform:
            image = self.post_geo_transform(image)

        # augmented_coords = gen_coordinates(coords, cfg.num_landmarks)
        augmented_coords = coords * cfg.model_image_size / cfg.image_size
        normalized_image = image*2 - 1

        return {
            "image": normalized_image,
            "points": augmented_coords,
            "heatmaps": coord_to_heatmap(augmented_coords, image.shape,
                                         cfg.num_landmarks, cfg.heatmap, "cpu"),
            "frame": frame_num
        }


