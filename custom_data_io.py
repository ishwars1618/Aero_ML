class RandomAdditiveNoise:
    def __init__(self, p=0.5, mean=0.0, std=0.05):
        self.p = p
        self.mean = mean
        self.std = std

    @classmethod
    def from_config(cls, noise):
        return cls(p=noise.p, mean=noise.mean, std=noise.std)

    def __call__(self, x):
        # x: tensor in [0,1], shape (C, H, W)
        if torch.rand(1).item() < self.p:
            noise = torch.randn_like(x) * self.std + self.mean
            x = x + noise
            x = torch.clamp(x, 0.0, 1.0)
        return x


class RandomColorMatrix:
    """
    Applies x -> A x where A is 3x3 with:
      - rank in {1, 2, 3} (each w.p. 1/3)
      - spectral norm <= max_spectral_norm
    """
    def __init__(self, max_spectral_norm=1.5, min_spectral_norm=0.75, jitter=0.1):
        self.max_spectral_norm = max_spectral_norm
        self.min_spectral_norm = min_spectral_norm
        self.jitter = jitter

    @classmethod
    def from_config(cls, color_matrix):
        return cls(max_spectral_norm=color_matrix.max_spectral_norm,
                   min_spectral_norm=color_matrix.min_spectral_norm,
                   jitter=color_matrix.jitter)

    def _random_orthonormal(self):
        """Generate a random 3x3 orthonormal matrix via QR."""
        M = torch.randn(3, 3)
        Q, _ = torch.linalg.qr(M)  # Q is orthonormal
        return Q

    def __call__(self, x):
        # x: tensor in [0,1], shape (3, H, W)
        c, h, w = x.shape
        assert c == 3, "RandomColorMatrix expects a 3-channel RGB tensor."

        # The full rank-sampling / SVD construction is disabled in the notebook;
        # what runs is the identity plus a small perturbation.
        A = torch.eye(c)
        A += torch.randn_like(A)*self.jitter

        # Apply A to each pixel: x_flat is 3 x (H*W)
        x_flat = x.view(3, -1)
        x_transformed = A @ x_flat
        x_out = x_transformed.view(3, h, w)

        # Clamp back to [0,1]
        x_out = torch.clamp(torch.abs(x_out), 0.0, 1.0)
        return x_out


class ComposeJoint:
    def __init__(self, transforms):
        self.transforms = transforms

    def __call__(self, img, pts):
        for t in self.transforms:
            img, pts = t(img, pts)
        return img, pts


class RandomAffineWithPoints:
    """
    Same params as torchvision.transforms.RandomAffine,
    but applied to both image and (N,2) coords.
    """
    def __init__(self, degrees, translate=None, scale=None, shear=None):
        self.degrees = degrees
        self.translate = translate
        self.scale = scale
        self.shear = shear

    @classmethod
    def from_config(cls, affine):
        return cls(degrees=affine.degrees, translate=affine.translate,
                   scale=affine.scale, shear=affine.shear)

    def __call__(self, img, pts):
        # img.size is (W, H)
        w, h = img.size()[1:]

        # Sample random params exactly like RandomAffine
        angle, translations, scale, shear = transforms.RandomAffine.get_params(
            self.degrees, self.translate, self.scale, self.shear, (w, h)
        )
        corner_pixel = (img[0, -1, -1].item(), img[1, -1, -1].item(), img[2, -1, -1].item())
        # --- 1) Transform the image ---
        img = TF.affine(
            img,
            angle=angle,
            translate=translations,
            scale=scale,
            shear=shear,
            interpolation = transforms.InterpolationMode.BILINEAR,
            fill=corner_pixel
        )

        center = [w * 0.5, h * 0.5]
        inv_coeffs = TF._get_inverse_affine_matrix(
            center=center,
            angle=angle,
            translate=translations,
            scale=scale,
            shear=shear
        )
        # inv_coeffs = [a, b, c, d, e, f] giving:
        # x_in  = a * x_out + b * y_out + c
        # y_in  = d * x_out + e * y_out + f
        a, b, c, d, e, f = inv_coeffs

        M_inv = torch.tensor(
            [[a, b],
             [d, e]],
            dtype=torch.float32,
            device=pts.device,
        )

        M = torch.inverse(M_inv)  # 2x2

        translation = torch.tensor([[c, f]]).repeat(pts.size()[0], 1)
        pts_tr = pts - translation
        pts_out = (M @ pts_tr.T).T

        return img, pts_out


def build_transforms(config):
    """The notebook's three-stage pipeline, built from config.

    Returns (transform, geo_transform, post_geo_transform).
    """
    transform = transforms.Compose([
        transforms.Resize(config.image_size),
        transforms.ToTensor(),
    ])
    geo_transform = ComposeJoint([
        RandomAffineWithPoints.from_config(config.affine),
    ])
    post_geo_transform = transforms.Compose([
        RandomColorMatrix.from_config(config.color_matrix),
        RandomAdditiveNoise.from_config(config.noise),
        transforms.Resize(config.model_image_size),
    ])
    return transform, geo_transform, post_geo_transform


