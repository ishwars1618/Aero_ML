def build_dataset(config=None):
    """The dataset the notebook builds, with every knob taken from config."""
    config = config or DataConfig.load()
    transform, geo_transform, post_geo_transform = build_transforms(config)
    return FramesFromCSV(config, transform=transform, geo_transform=geo_transform,
                         post_geo_transform=post_geo_transform)


def build_dataloaders(dataset, config=None, verbose=False):
    """Split `dataset` and wrap each part in a DataLoader.

    The split is seeded from config, so it reproduces the notebook's exactly.
    """
    config = config or DataConfig.load()
    split = config.split

    total_size = len(dataset)
    train_size = int(total_size * split.train)
    val_size = int(total_size * split.val)
    test_size = total_size - train_size - val_size  # Ensure all samples are used

    seed = torch.Generator().manual_seed(split.seed)
    train_dataset, val_dataset, test_dataset = random_split(
        dataset, [train_size, val_size, test_size], generator=seed)

    if verbose:
        print(f"Train size: {len(train_dataset)}")
        print(f"Validation size: {len(val_dataset)}")
        print(f"Test size: {len(test_dataset)}")

    train_loader = DataLoader(train_dataset, batch_size=config.batch_size,
                              shuffle=True, num_workers=config.workers)
    val_loader = DataLoader(val_dataset, batch_size=config.batch_size,
                            shuffle=False, num_workers=config.workers)
    test_loader = DataLoader(test_dataset, batch_size=config.batch_size,
                             shuffle=False, num_workers=config.workers)
    return train_loader, val_loader, test_loader
