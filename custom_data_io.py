@dataclass(frozen=True)
class HeatmapConfig:
    """Gaussian target heatmaps.

    Only `max_sigma` is live. `min_sigma` and `sigma_ratio` feed the
    distance-adaptive sigma the notebook has commented out in coord_to_heatmap;
    they are kept so that experiment can be switched back on from config.
    """
    max_sigma: float = 5.0
    min_sigma: float = 1.0
    sigma_ratio: float = 0.05


@dataclass(frozen=True)
class AffineConfig:
    degrees: Tuple[float, float] = (-180.0, 180.0)
    translate: Tuple[float, float] = (0.0, 0.0)
    scale: Tuple[float, float] = (1.3, 1.5)
    shear: Tuple[float, float] = (-7.0, 7.0)


@dataclass(frozen=True)
class ColorMatrixConfig:
    max_spectral_norm: float = 1.5
    min_spectral_norm: float = 0.95
    # Std of the perturbation added to the identity colour matrix.
    jitter: float = 0.1


@dataclass(frozen=True)
class NoiseConfig:
    p: float = 0.7
    mean: float = 0.0
    std: float = 0.025


@dataclass(frozen=True)
class SplitConfig:
    train: float = 0.8
    val: float = 0.1
    seed: int = 42


@dataclass(frozen=True)
class DataConfig:
    image_size: int = 324
    model_image_size: int = 128
    num_landmarks: int = 5
    batch_size: int = 16
    # The notebook declared workers=2 but never passed it to DataLoader; 0 keeps
    # the behaviour it actually ran with.
    workers: int = 0

    # Which model to build; a key of model_registry.MODELS.
    model: str = "unet"
    rootdir: str = "/Users/ishwar/Downloads"
    output_dir: str = "model_output_090526_128x128_unet"

    # Optimizer settings. These are per-architecture: the U-Net was tuned at
    # 0.0005 / 0.5, the transformer at 0.0002 / 0.1.
    lr: float = 0.0005
    clip_max_norm: float = 0.5

    # Checkpoint to load for inference/examination, relative to output_dir.
    checkpoint: str = "info_model_060626_1000.pt"
    num_epochs: int = 1000

    csv_path: str = "plane_data/labeled_points_mega_grp.csv"
    images_dir: str = "outp"
    image_pattern: str = "frame_{frame}.png"

    heatmap: HeatmapConfig = field(default_factory=HeatmapConfig)
    affine: AffineConfig = field(default_factory=AffineConfig)
    color_matrix: ColorMatrixConfig = field(default_factory=ColorMatrixConfig)
    noise: NoiseConfig = field(default_factory=NoiseConfig)
    split: SplitConfig = field(default_factory=SplitConfig)

    @classmethod
    def from_dict(cls, d):
        """Build from a plain dict, recursing into the nested config sections.

        Unknown keys are an error rather than being ignored, so a typo in the
        JSON surfaces immediately instead of silently leaving a default in place.
        """
        return _from_dict(cls, d)

    @classmethod
    def load(cls, path=CONFIG_PATH):
        with open(path) as f:
            return cls.from_dict(json.load(f))

    def save(self, path=CONFIG_PATH):
        with open(path, "w") as f:
            json.dump(asdict(self), f, indent=2)
            f.write("\n")

    def replace(self, **kw):
        """A copy with overrides, e.g. cfg.replace(batch_size=8)."""
        return _from_dict(type(self), {**asdict(self), **kw})


def _from_dict(cls, d):
    known = {f.name: f for f in fields(cls)}
    unknown = set(d) - set(known)
    if unknown:
        raise ValueError(f"{cls.__name__}: unknown config keys {sorted(unknown)}")
    kw = {}
    for name, value in d.items():
        ftype = known[name].type
        if is_dataclass(ftype) and isinstance(value, dict):
            kw[name] = _from_dict(ftype, value)
        elif isinstance(value, list):
            kw[name] = tuple(value)
        else:
            kw[name] = value
    return cls(**kw)


